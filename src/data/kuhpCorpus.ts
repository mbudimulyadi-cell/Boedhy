export interface ValidationResult {
  valid: boolean;
  pasalNumber?: number;
  matchedArticle?: CorpusArticle;
  wvsMatch?: CorpusArticle;
  message?: string;
  suggestions: CorpusArticle[];
}

export function extractPasalNumber(input: string): number | null {
  const match = input.match(/\bpasal\s+(\d+)\b/i) ?? input.match(/^\s*(\d+)\s*$/);
  if (!match) return null;
  const num = Number.parseInt(match[1], 10);
  return Number.isNaN(num) ? null : num;
}

export function isPasalSpecificQuery(query: string): boolean {
  const trimmed = query.trim();
  if (!trimmed) return false;
  return extractPasalNumber(trimmed) !== null;
}

