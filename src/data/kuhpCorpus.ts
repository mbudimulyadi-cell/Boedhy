export function findRelevantCorpusArticles(query: string, limit = 8): CorpusArticle[] {
  const normalized = query.toLowerCase().trim();
  const num = extractPasalNumber(normalized);

  const exactNum = num !== null ? KUHP_CORPUS.find((a) => a.nomorAngka === num) : undefined;
  const wvsMatched =
    num !== null
      ? KUHP_CORPUS.filter((a) => a.wvsPadanan && new RegExp(`\\b${num}\\b`).test(a.wvsPadanan))
      : [];

  const rawTokens = normalized
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')
    .split(/\s+/)
    .filter((t) => t.length >= 3);

  const expandedTokens = new Set<string>(rawTokens);
  for (const tok of rawTokens) {
    const syns = KEYWORD_SYNONYMS[tok];
    if (syns) {
      for (const s of syns) expandedTokens.add(s);
    }
  }

  const scored: { art: CorpusArticle; score: number }[] = [];

  for (const a of KUHP_CORPUS) {
    if (exactNum && a.nomorAngka === exactNum.nomorAngka) continue;
    if (wvsMatched.some((w) => w.pasal === a.pasal)) continue;

    let score = 0;
    const judulL = a.judul.toLowerCase();
    const bunyiL = a.bunyi.toLowerCase();
    const penL = a.penjelasan.toLowerCase();
    const wvsL = (a.wvsPadanan ?? '').toLowerCase();

    if (judulL.includes(normalized)) score += 12;
    if (a.kataKunci.some((kw) => kw.toLowerCase() === normalized)) score += 15;
    if (a.kataKunci.some((kw) => kw.toLowerCase().includes(normalized) || normalized.includes(kw.toLowerCase()))) {
      score += 8;
    }
    if (bunyiL.includes(normalized) || penL.includes(normalized) || wvsL.includes(normalized)) {
      score += 4;
    }

    for (const tok of expandedTokens) {
      if (a.kataKunci.some((kw) => kw.toLowerCase() === tok)) score += 7;
      else if (a.kataKunci.some((kw) => kw.toLowerCase().includes(tok))) score += 4;
      if (judulL.includes(tok)) score += 4;
      if (bunyiL.includes(tok) || penL.includes(tok)) score += 2;
    }

    if (score > 0) {
      scored.push({ art: a, score });
    }
  }

  scored.sort((a, b) => b.score - a.score || a.art.nomorAngka - b.art.nomorAngka);

  const combined: CorpusArticle[] = [];
  if (exactNum) combined.push(exactNum);
  for (const w of wvsMatched) {
    if (!combined.some((c) => c.pasal === w.pasal)) combined.push(w);
  }
  for (const item of scored) {
    if (!combined.some((c) => c.pasal === item.art.pasal)) combined.push(item.art);
  }
  return combined.slice(0, limit);
}

export function validatePasalInput(
  query: string,
  moduleMode: 'bedah-pasal' | 'komparator' | 'other'
): ValidationResult {
  const trimmed = query.trim();
  if (!trimmed) {
    return {
      valid: false,
      message:
        'Mohon masukkan nomor pasal (contoh: "Pasal 458" atau "Pasal 476") atau kata kunci tindak pidana (contoh: "Pembunuhan").',
      suggestions: KUHP_CORPUS.filter((a) => [458, 476, 492, 433].includes(a.nomorAngka)),
    };
  }

  const num = extractPasalNumber(trimmed);
  if (num !== null && (num < 1 || num > TOTAL_PASAL_UU_1_2023)) {
    return {
      valid: false,
      pasalNumber: num,
      message: `Pasal ${num} tidak ditemukan dalam korpus UU No. 1 Tahun 2023 jo. UU No. 1 Tahun 2026. UU No. 1 Tahun 2023 terdiri dari Pasal 1 sampai dengan Pasal ${TOTAL_PASAL_UU_1_2023}. Silakan periksa kembali nomor pasal atau pilih rujukan di bawah ini.`,
      suggestions: KUHP_CORPUS.filter((a) => [458, 459, 476, 486, 492].includes(a.nomorAngka)),
    };
  }

  const exact = num !== null ? KUHP_CORPUS.find((a) => a.nomorAngka === num) : undefined;
  const wvsMatch =
    num !== null
      ? KUHP_CORPUS.find((a) => a.wvsPadanan && new RegExp(`\\b${num}\\b`).test(a.wvsPadanan))
      : undefined;

  if (moduleMode === 'bedah-pasal' && !exact && wvsMatch) {
    return {
      valid: true,
      pasalNumber: num ?? undefined,
      wvsMatch,
      message: `Catatan: Pasal ${num} merupakan penomoran populer dalam KUHP Lama (WvS). Dalam UU No. 1 Tahun 2023 jo. UU No. 1 Tahun 2026, substansi tersebut bersesuaian dengan ${wvsMatch.pasal} (${wvsMatch.judul}).`,
      suggestions: [wvsMatch],
    };
  }

  return {
    valid: true,
    pasalNumber: num ?? undefined,
    matchedArticle: exact,
    wvsMatch,
    suggestions: findRelevantCorpusArticles(trimmed, 8),
  };
}
